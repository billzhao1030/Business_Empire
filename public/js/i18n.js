export let lang = localStorage.getItem('be_lang') || 'zh';
const listeners = new Set();
export function onLangChange(fn) { listeners.add(fn); }
export function setLang(l) {
  lang = l; localStorage.setItem('be_lang', l);
  document.documentElement.lang = l === 'zh' ? 'zh-CN' : 'en';
  listeners.forEach(f => f(l));
}
export function t(path, params) {
  const parts = path.split('.');
  let v = DICT[lang];
  for (const k of parts) { v = v?.[k]; if (v === undefined) break; }
  if (v === undefined) { v = DICT.zh; for (const k of parts) v = v?.[k]; }
  if (typeof v !== 'string') return v ?? path;
  return params ? v.replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '') : v;
}
